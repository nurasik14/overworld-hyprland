#!/usr/bin/env bash
# apps/zen/build.sh — generate apps/zen/overworld.css (chrome) + apps/zen/overworld-content.css (about: pages) from the tokens:
#   Day  = tokens/out/light/zen-vars.css at :root (default)
#   Night = tokens/out/dark/zen-vars.css wrapped in @media (prefers-color-scheme: dark)
#   then the hand-written rules (userChrome-rules.css / userContent-rules.css).
# One file serves both modes: Zen follows the desktop colour scheme through the portal, so apply-mode.sh only has to set
# gsettings color-scheme. The variables are inlined (no @import). Pure bash + python3 stdlib; idempotent.
# install.sh COPIES the results into the profile's chrome/ (the flatpak sandbox cannot follow symlinks into ~/.config/overworld).
set -euo pipefail
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
tokens="$here/../../tokens/out"
strip() { grep -vE '^\s*/\*.*\*/\s*$' "$1"; }   # drop the generator comment lines

# the generated variables block (Day default, Night in the media query); $1 = indent
vars_block() {
  local ind="$1"
  {
    echo "/* ---- Day: light-grey GUI panel ---- */"
    strip "$tokens/light/zen-vars.css"
    echo "/* ---- Night: deepslate ---- */"
    echo "@media (prefers-color-scheme: dark) {"
    strip "$tokens/dark/zen-vars.css" | sed 's/^/  /'
    echo "}"
  } | sed "s/^/$ind/"
}

{
  echo "/* Overworld Hyprland — Zen userChrome (Minecraft GUI). GENERATED by apps/zen/build.sh from tokens/out/{light,dark}/zen-vars.css + apps/zen/userChrome-rules.css — edit those. */"
  vars_block ""
  echo
  cat "$here/userChrome-rules.css"
} > "$here/overworld.css"

# userContent: the same variables, but scoped inside the rules' @-moz-document so they never reach ordinary websites
vars_tmp="$(mktemp)"; trap 'rm -f "$vars_tmp"' EXIT
vars_block "  " > "$vars_tmp"
{
  echo "/* Overworld Hyprland — Zen userContent (about: pages only). GENERATED by apps/zen/build.sh — edit apps/zen/userContent-rules.css. */"
  python3 -I - "$here/userContent-rules.css" "$vars_tmp" <<'PY'
import sys
rules = open(sys.argv[1], encoding="utf-8").read()
vars_ = open(sys.argv[2], encoding="utf-8").read().rstrip("\n")
marker = "/* @OW_VARS@ */"
if marker not in rules:
    sys.exit("build.sh: marker %r missing from userContent-rules.css" % marker)
sys.stdout.write(rules.replace(marker, vars_.lstrip(), 1))
PY
} > "$here/overworld-content.css"

echo "built: $here/overworld.css ($(wc -l < "$here/overworld.css") lines), $here/overworld-content.css ($(wc -l < "$here/overworld-content.css") lines)"
